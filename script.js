// ---------- 鱼缸行的四个下拉（柜体颜色 / 岩板 / 溢流方向 / 底滤） ----------

// 把一个选项列表填进 <select>：第一个是灰色提示（占位），后面是真实选项
// 从"缸型 尺寸"型号字符串里提取缸型（如 'LF 1530*680*690/1000' → 'LF'）
function fishTypeOf(model) {
  if (!model) return '';
  const m = model.match(/^(.*?)\s+\d/);
  return m ? m[1] : '';
}

function fillFishDropdown(sel, list, phText) {
  sel.innerHTML = '';
  const ph = document.createElement('option');
  ph.value = '';
  ph.textContent = phText;
  ph.selected = true;
  sel.appendChild(ph);
  for (const t of list) {
    const opt = document.createElement('option');
    opt.value = t;
    opt.textContent = t;
    sel.appendChild(opt);
  }
}

// 按当前品牌，给鱼缸行填好四个下拉的选项
function fillFishOptions(row, brand) {
  const cfg = fishConfig[brand];
  if (!cfg) return;
  const modelSel0 = row.querySelector('.model');
  const model = modelSel0 ? modelSel0.value : '';
  const type = fishTypeOf(model);
  // 优先按型号取（满堂鸿的底滤/底柜），再按缸型取（虎鲸），最后品牌级（形水/水鸦）
  const pick = function (key) {
    if (key === 'filter' && cfg.filterMap && cfg.filterMap[model]) return cfg.filterMap[model];
    if (key === 'base' && cfg.baseMap && cfg.baseMap[model]) return cfg.baseMap[model];
    const byType = cfg[key + 'ByType'];
    if (byType && byType[type]) return byType[type];
    return cfg[key] || [];
  };
  // 重填时保留仍在新选项里的原选择（换缸型选项变了才需要重选）
  const refill = function (key, phText) {
    const sel = row.querySelector('.fish-opt[data-fish="' + key + '"]');
    const prev = sel.value;
    fillFishDropdown(sel, pick(key), phText);
    let keep = false;
    for (let i = 0; i < sel.options.length; i++) {
      if (sel.options[i].value !== '' && sel.options[i].value === prev) { keep = true; break; }
    }
    if (keep) sel.value = prev;
  };
  // 溢流不保留旧值：单选项（背溢流）自动选中，多选项（左/右）默认不选
  const flowSel2 = row.querySelector('.fish-opt[data-fish="flow"]');
  if (flowSel2) fillFishDropdown(flowSel2, pick('flow'), '溢流方向');
  refill('cabinet', '柜体颜色');
  // 柜门款式：仅配置了 door 的品牌（中鼎）显示，其余隐藏
  const doorSel = row.querySelector('.fish-opt[data-fish="door"]');
  const doorList = cfg.door || [];
  if (doorSel) {
    if (doorList.length) {
      const optsBox = doorSel.closest('.fish-options');
      if (optsBox) optsBox.classList.add('five'); // 5 个下拉同一行
      doorSel.style.display = '';
      if (doorSel.parentElement) doorSel.parentElement.style.display = '';
      const prevDoor = doorSel.value;
      fillFishDropdown(doorSel, doorList, '柜门款式');
      let keepDoor = false;
      for (let i = 0; i < doorSel.options.length; i++) {
        if (doorSel.options[i].value !== '' && doorSel.options[i].value === prevDoor) { keepDoor = true; break; }
      }
      if (keepDoor) doorSel.value = prevDoor;
    } else {
      doorSel.style.display = 'none';
      if (doorSel.parentElement) doorSel.parentElement.style.display = 'none';
      doorSel.value = '';
    }
  }
  refill('rock', '岩板颜色');
  refill('filter', '底滤');
  // 底柜（满堂鸿）：按型号取选项；显示时加入 5 列，否则隐藏并恢复 4 列（需柜门也隐藏）
  const baseSel = row.querySelector('.fish-opt[data-fish="base"]');
  const baseList = (cfg.baseMap && cfg.baseMap[model]) || [];
  if (baseSel) {
    if (baseList.length) {
      const optsBox = baseSel.closest('.fish-options');
      if (optsBox) optsBox.classList.add('five'); // 5 个下拉同一行
      baseSel.style.display = '';
      if (baseSel.parentElement) baseSel.parentElement.style.display = '';
      const prevBase = baseSel.value;
      fillFishDropdown(baseSel, baseList, '底柜');
      let keepBase = false;
      for (let i = 0; i < baseSel.options.length; i++) {
        if (baseSel.options[i].value !== '' && baseSel.options[i].value === prevBase) { keepBase = true; break; }
      }
      if (keepBase) baseSel.value = prevBase;
    } else {
      baseSel.style.display = 'none';
      if (baseSel.parentElement) baseSel.parentElement.style.display = 'none';
      baseSel.value = '';
      // 柜门也没显示 → 恢复 4 列
      const optsBox = baseSel.closest('.fish-options');
      const doorSel2 = row.querySelector('.fish-opt[data-fish="door"]');
      const doorStill = doorSel2 && doorSel2.style.display !== 'none';
      if (optsBox && !doorStill) optsBox.classList.remove('five');
    }
  }
  applyFilterLimit(row); // 按当前型号处理底滤限制
  applyFlowLock(row);    // 按当前型号处理溢流锁定

  // 所有下拉统一规则：只有一个选项时默认直接选中（如方缸"背溢流"、M7"工业风"、国潮方缸"手绘国粹风"、中鼎方缸"满仓底滤"）；
  // 有两个及以上可选的一律保持不选（灰色提示），由销售手动选择
  row.querySelectorAll('.fish-opt').forEach(function (sel) {
    if (sel.style.display === 'none') return;
    if (sel.value !== '') return;
    const rs = Array.prototype.filter.call(sel.options, function (o) { return o.value !== ''; });
    if (rs.length === 1) sel.value = rs[0].value;
  });
}

// 底滤限制（按品牌配置）：命中尺寸的型号禁用某些底滤选项，并强制切回允许值
function applyFilterLimit(row) {
  const brandSel = row.querySelector('.brand');
  const modelSel = row.querySelector('.model');
  const filterSel = row.querySelector('.fish-opt[data-fish="filter"]');
  if (!modelSel || !filterSel) return;
  const brand = brandSel ? brandSel.value : '';
  const cfg = fishConfig[brand] || null;
  const model = modelSel.value || '';
  // 优先按缸型取限制规则（虎鲸），没有则退回品牌级（形水/水鸦）
  const flT = (cfg && cfg.filterLimitByType && cfg.filterLimitByType[fishTypeOf(model)]) || null;
  const fl = flT || (cfg && cfg.filterLimit) || null;
  if (!fl) return;
  const matched = fl.sizeMatch.some(function (s) { return model.indexOf(s) >= 0; });
  for (const opt of filterSel.options) {
    if (opt.value === '') { opt.disabled = false; continue; } // 灰色提示选项不禁用
    opt.disabled = !!matched && fl.forbidden.indexOf(opt.value) >= 0;
  }
  // 若当前选中的是被禁用的，强制切回允许的那一种
  if (matched && fl.forbidden.indexOf(filterSel.value) >= 0) {
    filterSel.value = fl.fallback;
  }
}

// 溢流规则（按品牌配置）：
// - 命中类型+尺寸的型号（如水鸦金鱼缸/溪流缸 600、800）→ 锁定"背溢流"，其他选项禁用
// - 其他型号 → 禁用 elseForbidden 里的选项（如水鸦其余型号禁"背溢流"，只能左/右）
function applyFlowLock(row) {
  const brandSel = row.querySelector('.brand');
  const modelSel = row.querySelector('.model');
  const flowSel = row.querySelector('.fish-opt[data-fish="flow"]');
  if (!modelSel || !flowSel) return;
  const brand = brandSel ? brandSel.value : '';
  const cfg = fishConfig[brand] || null;
  const model = modelSel.value || '';
  const fl = (cfg && cfg.flowLock) || null;
  const locked = fl &&
    fl.sizeMatch.some(function (s) { return model.indexOf(s) >= 0; }) &&
    fl.typeMatch.some(function (t) { return model.indexOf(t) >= 0; });
  for (const opt of flowSel.options) {
    if (opt.value === '') { opt.disabled = false; continue; } // 灰色提示选项不禁用
    if (locked) {
      opt.disabled = opt.value !== fl.value;                       // 锁定：只能选指定值
    } else if (fl && fl.elseForbidden) {
      opt.disabled = fl.elseForbidden.indexOf(opt.value) >= 0;     // 非锁定：禁用这些选项
    } else {
      opt.disabled = false;
    }
  }
  if (locked && flowSel.value !== fl.value) {
    flowSel.value = fl.value;                                      // 锁定型号：强制背溢流
  } else if (!locked && fl && fl.elseForbidden.indexOf(flowSel.value) >= 0) {
    for (const opt of flowSel.options) {                           // 切型号残留被禁选项：自动切到第一个可用项
      if (opt.value !== '' && !opt.disabled) { flowSel.value = opt.value; break; }
    }
  }
}

