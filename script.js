    var bMan = row.querySelector('.brand-manual');
    if (bSel && bSel.value) brand = (bSel.value === '__other__') ? ((bMan || {}).value || '').trim() : bSel.value;
    else if (bMan) brand = bMan.value.trim();
    // 型号
    var model = '';
    var mSel = row.querySelector('.model');
    var mMan = row.querySelector('.model-manual');
    if (mSel && mSel.value) model = (mSel.value === '__other__') ? ((mMan || {}).value || '').trim() : mSel.value;
    else if (mMan) model = mMan.value.trim();
