// ---------- 订单号：Dy + 年月日 + 当天序号（如 Dy20260905-001） ----------
// 打开页面只"预览"下一号（不占用）；点击提交且校验通过时才正式递增并保存
function genOrderNo(commit, ownerCode) {
  const now = new Date();
  const p2 = (n) => String(n).padStart(2, '0');
  const p3 = (n) => String(n).padStart(3, '0');
  const ymd = now.getFullYear() + p2(now.getMonth() + 1) + p2(now.getDate());
  const key = 'dyOrderSeq_' + ymd;
  const seq = (parseInt(localStorage.getItem(key) || '0', 10) || 0) + 1;
  if (commit) { try { localStorage.setItem(key, String(seq)); } catch (e) {} }
  const tag = (ownerCode || '').trim() ? ownerCode.trim() : '';
  return 'Dy' + ymd + '-' + tag + p3(seq);
}
