function updateRowState(row) {
  const catSel = row.querySelector('.cat');
  const brandSel = row.querySelector('.brand');
  const modelSel = row.querySelector('.model');
  const origBox = row.querySelector('.orig');
  const catManualInput = row.querySelector('.cat-manual');
  const brandManualInput = row.querySelector('.brand-manual');
  const modelManualInput = row.querySelector('.model-manual');
  const catRestore = row.querySelector('.cat-wrap .restore');
  const brandRestore = row.querySelector('.brand-wrap .restore');
  const modelRestore = row.querySelector('.model-wrap .restore');
  if (!origBox) return; // 物流费/安装费等没有原价格的行直接跳过

  const catOther = catSel ? catSel.value === '__other__' : false;
  const brandOther = brandSel ? brandSel.value === '__other__' : false;
  const modelOther = modelSel ? modelSel.value === '__other__' : false;
  const isDikou = catSel ? catSel.value === '抵扣' : false;   // 抵扣行：品牌/型号是文本框，原价仍自动

  const brandManual = isDikou || catOther || brandOther;     // 品牌要不要手动
  const modelManual = isDikou || brandManual || modelOther;  // 型号要不要手动
  const origManual = (!isDikou) && modelManual;              // 原价要不要手动（抵扣行保持自动）

  // 类别格：新增行才有下拉；固定行是文字，不用动
  if (catSel && catManualInput) {
    catSel.style.display = catOther ? 'none' : 'block';
    catManualInput.style.display = catOther ? 'block' : 'none';
    refreshRestore(row, 'cat');
  }

  // 品牌格
  if (brandSel && brandManualInput) {
    brandSel.style.display = brandManual ? 'none' : 'block';
    brandManualInput.style.display = brandManual ? 'block' : 'none';
    refreshRestore(row, 'brand');
  }

  // 型号格
  if (modelSel && modelManualInput) {
    modelSel.style.display = modelManual ? 'none' : 'block';
    modelManualInput.style.display = modelManual ? 'block' : 'none';
    refreshRestore(row, 'model');
  }

  // 原价：手动模式下可手填，正常模式自动算
  if (origManual) {
    origBox.readOnly = false;
    origBox.classList.add('editable');
  } else {
    origBox.readOnly = true;
    origBox.classList.remove('editable');
    // 回到正常模式时，清空之前手填的内容（抵扣行除外：它的品牌/型号文本框是常态，不清空）
    if (!isDikou) {
      if (catManualInput) catManualInput.value = '';
      if (brandManualInput) brandManualInput.value = '';
      if (modelManualInput) modelManualInput.value = '';
    }
  }

  // 鱼缸行：品牌选"其他"→ 备注四个下拉换成手动文本框；选回正常→恢复
  const fishOptions = row.querySelector('.fish-options');
  const fishFreeNote = row.querySelector('.fish-free-note');
  if (fishOptions && fishFreeNote) {
    const fishManual = brandOther; // 只有品牌选"其他"才切
    fishOptions.style.display = fishManual ? 'none' : 'grid';
    fishFreeNote.style.display = fishManual ? 'block' : 'none';
    if (fishManual) autoResize(fishFreeNote);
  }
}

