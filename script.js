// 计算一行的"原价"（只读、自动出现），并返回这行的原价金额
function calcOriginal(row) {
  const brand = row.querySelector('.brand').value.trim();
  const model = row.querySelector('.model').value.trim();
  const qty = parseFloat(row.querySelector('.qty').value) || 0;

  const unitPrice = priceList[brand + '|' + model]; // 按 品牌+型号 查价格表
  const box = row.querySelector('.orig');

  if (!unitPrice || qty <= 0) { box.value = ''; return 0; }

  const val = unitPrice * qty; // 原价 = 原单价 × 数量
  box.value = val.toFixed(2);  // 显示两位小数
  return val;
}

// 重算整张表
function recalc() {
  let sumAmount = 0; // 合计金额
  let sumOrig = 0;   // 合计原价

  for (let row of allRows()) {
    // 物流费 / 安装费：只填单价，原价 = 总价 = 单价（数量固定按 1）
    if (row.classList.contains('fee-row')) {
      const price = parseFloat(row.querySelector('.price').value) || 0;
      row.querySelector('.amount').value = price === 0 ? '' : fmt(price);
      row.querySelector('.orig').value = price === 0 ? '' : fmt(price);
      sumAmount = sumAmount + price;
      sumOrig = sumOrig + price;
      continue; // 这行算完了，去下一行
    }

    // 鱼缸固定行：单价 = 原价（自动算，不允许填写）
    if (row.getAttribute('data-category') === '鱼缸') {
      const qty = parseFloat(row.querySelector('.qty').value) || 0;
      const catSel0 = row.querySelector('.cat');
      const catOther = catSel0 ? catSel0.value === '__other__' : false;
      const brandOther = row.querySelector('.brand').value === '__other__';
      const modelOther = row.querySelector('.model').value === '__other__';
      const brand = row.querySelector('.brand').value;
      const model = row.querySelector('.model').value;
      const cfg = fishConfig[brand] || null;
      let orig;
      if (catOther || brandOther || modelOther) {
        // 选了"其他"：按手填的原价算（不再自动加价）
        orig = parseFloat(row.querySelector('.orig').value) || 0;
      } else if (cfg) {
        // 正常：基础原价（型号查表）+ 岩板加价
        const rock = row.querySelector('.fish-opt[data-fish="rock"]').value;
        let base;
        if (cfg.comboBase) {
          // 满堂鸿：价格 = 型号 + 底柜 + 底滤 组合
          const baseCab = (row.querySelector('.fish-opt[data-fish="base"]') || {}).value || '';
          const filterVal = (row.querySelector('.fish-opt[data-fish="filter"]') || {}).value || '';
          base = cfg.comboBase[model + '|' + baseCab + '|' + filterVal] || 0;
        } else {
          base = cfg.basePrice[model] !== undefined
            ? cfg.basePrice[model]
            : (priceList[brand + '|' + model] || 0);
        }
        const extra = ((cfg.rockExtraList || []).indexOf(rock) >= 0) ? (cfg.rockExtra || 0) : 0; // 岩板加价（按品牌配置）
        orig = base + extra;
      } else {
        // 该品牌没配鱼缸表：退回普通查价
        orig = calcOriginal(row);
      }
      const price = orig;              // 单价 = 原价
      const amount = price * qty;      // 总价 = 单价 × 数量
      row.querySelector('.orig').value = price === 0 ? '' : fmt(price);
      row.querySelector('.price').value = price === 0 ? '' : fmt(price);
      row.querySelector('.amount').value = amount === 0 ? '' : fmt(amount);
      sumOrig = sumOrig + price;
      sumAmount = sumAmount + amount;
      continue; // 这行算完了，去下一行
    }

    // 普通行：总价 = 数量 × 单价
    const qty = parseFloat(row.querySelector('.qty').value) || 0;
    const priceBox = row.querySelector('.price');
    const priceRaw = (priceBox.value || '').trim();
  const price = parseFloat(priceRaw) || 0;
    const amount = qty * price;
    row.querySelector('.amount').value = amount === 0 ? '' : fmt(amount);
    sumAmount = sumAmount + amount;

    // 新增行：单价未填（总价空）→ 备注自动红色"赠送"；单价填了则清掉自动标记
    const remark = row.querySelector('.remark');
    if (remark) {
      if (priceBox.value.trim() === '') {
        if (remark.value.trim() === '') {
          remark.value = '赠送';
          remark.classList.add('free-mark');
          autoResize(remark);
        }
      } else if (remark.value === '赠送' && remark.classList.contains('free-mark')) {
        remark.value = '';
        remark.classList.remove('free-mark');
      }
    }

    // 原价：抵扣行 → 原价 = 总价（单价为负）；其他 → 类别/品牌/型号任一个选"其他"按手填，否则自动按价格表算
    const catSel0 = row.querySelector('.cat');
    const catOther = catSel0 ? catSel0.value === '__other__' : false;
    const brandOther = row.querySelector('.brand').value === '__other__';
    const modelOther = row.querySelector('.model').value === '__other__';
    if (rowCategory(row) === '抵扣') {
      row.querySelector('.orig').value = amount === 0 ? '' : fmt(amount);
      sumOrig = sumOrig + amount;
    } else if (catOther || brandOther || modelOther) {
      const manualOrig = parseFloat(row.querySelector('.orig').value) || 0;
      sumOrig = sumOrig + manualOrig;
    } else {
      sumOrig = sumOrig + calcOriginal(row);
    }

    // 单价不得高于原价：超出自动降到原价（合计金额同步修正）
    const curOrig = parseFloat(row.querySelector('.orig').value) || 0;
    if (curOrig > 0 && price > curOrig) {
      priceBox.value = fmt(curOrig);
      const newAmount = qty * curOrig;
      row.querySelector('.amount').value = newAmount === 0 ? '' : fmt(newAmount);
      sumAmount = sumAmount - amount + newAmount;
    }
  }

  totalBox.value = sumAmount === 0 ? '' : fmt(sumAmount);
  totalOrigBox.value = sumOrig === 0 ? '' : fmt(sumOrig);

  checkPrices();   // 价格校验
  checkDeposit();  // 定金 ≥ 鱼缸总价 50% 校验
}

// 价格校验：
// 1. 合计原价不得低于合计金额
// 2. 最终价格（手填）不得高于合计金额
function checkPrices() {
  const orig = parseFloat(totalOrigBox.value) || 0;
  const amt = parseFloat(totalBox.value) || 0;
  const fin = parseFloat(finalPriceBox.value) || 0;

  let msg = '';
  if (orig > 0 && amt > 0 && orig < amt) {
    msg = '警告：合计原价（' + orig + '）不得低于合计金额（' + amt + '）';
  }
  if (fin > 0 && amt > 0 && fin > amt) {
    msg = (msg ? msg + '<br>' : '') + '警告：最终价格（' + fin + '）不得高于合计金额（' + amt + '）';
  }

  warningBox.innerHTML = msg;
  warningBox.style.display = msg ? 'block' : 'none';
}

