// 把 "2026-06-17" 这种字符串转成毫秒数（手动拆开，避免时区误差）
function dateToMs(v) {
  const p = v.split('-');
  return new Date(+p[0], +p[1] - 1, +p[2]).getTime();
}

function calcLeadTime() {
  const a = orderDateBox.value;
  const b = expectDateBox.value;
  if (!a || !b) { leadTimeBox.value = ''; return; } // 有一个没选就留空

  const days = Math.round((dateToMs(b) - dateToMs(a)) / 86400000); // 1天 = 86400000 毫秒
  if (days < 0) { leadTimeBox.value = ''; return; } // 交付日期早于下单日期，视为无效

  leadTimeBox.value = days + '天';
}

