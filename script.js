// ---------- 重复产品检测：类别+品牌+型号 相同 → 相关行全部红色标注 ----------
function rowProductKey(row) {
  const cat = rowCategory(row);
  if (cat === '抵扣') return null; // 抵扣行是文本备注性质，不参与重复检测
  const bSel = row.querySelector('.brand');
  const bMan = row.querySelector('.brand-manual');
  const brand = (bSel && bSel.value)
    ? ((bSel.value === '__other__') ? ((bMan || {}).value || '').trim() : bSel.value.trim())
    : (bMan ? bMan.value.trim() : '');
  const mSel = row.querySelector('.model');
  const mMan = row.querySelector('.model-manual');
  const model = (mSel && mSel.value)
    ? ((mSel.value === '__other__') ? ((mMan || {}).value || '').trim() : mSel.value.trim())
    : (mMan ? mMan.value.trim() : '');
  if (!brand && !model) return null;
  return cat + '|' + brand + '|' + model;
}

function detectDuplicates() {
  const groups = {};
  allRows().forEach(function (row) {
    if (row.classList.contains('fee-row')) return; // 物流/安装固定行不参与
    const key = rowProductKey(row);
    if (!key) return;
    (groups[key] = groups[key] || []).push(row);
  });
  const dupSet = new Set(); // 收集重复的行（用 Set，避免 DOM 元素做对象 key 的坑）
  for (const k in groups) {
    if (groups[k].length > 1) {
      groups[k].forEach(function (r) { dupSet.add(r); });
    }
  }
  allRows().forEach(function (row) {
    const isDup = dupSet.has(row);
    row.classList.toggle('dup-row', isDup);
    const noTd = row.querySelector('td.no');
    let tag = noTd ? noTd.querySelector('.dup-tag') : null;
    if (isDup && !tag) {
      const s = document.createElement('span');
      s.className = 'dup-tag';
      s.textContent = '重复';
      noTd.appendChild(s);
    } else if (!isDup && tag) {
      tag.remove();
    }
  });
  return dupSet.size > 0;
}

